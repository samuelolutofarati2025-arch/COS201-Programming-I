package week03;

public class OperatorPractice {
    public static void main(String[] args) {

        int number1 = 10;
        int number2 = 5;

        //Arithmetic operators
        System.out.println(number1 + number2);
        System.out.println(number1 - number2);
        System.out.println(number1 * number2);
        System.out.println(number1 / number2);
        System.out.println(number1 % number2);

        // Relational operators
        System.out.println(number1 > number2);
        System.out.println(number1 < number2);

        // Logical operators
        int age = 20;

        System.out.println(age >= 18 && age <= 25);

    }
}